#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""repo_map.py - компактная «карта репозитория» для загрузки в проект Claude.

Python 3.8+, только stdlib. Запуск из корня репо:
    python tools/repo_map.py            -> пишет REPO_MAP.md
    python tools/repo_map.py --max 300  -> не более 300 символов-имён на файл

Что в карте: размеры/строки файлов, порядок <script> из index.html,
индекс верхнеуровневых функций/констант (имя:строка) для .js, число правил CSS.
Карта нужна, чтобы Claude знал, ЧТО где лежит, не читая файлы целиком.
"""
import argparse
import io
import os
import re
import sys

if sys.version_info < (3, 8):
    sys.exit("Нужен Python 3.8+")

SKIP_DIRS = set([".git", "node_modules", "__pycache__", ".vscode", "img"])
SKIP_PATHS = set(["temp", "tools/old", "patches/processed"])  # пути от корня, через /
SKIP_EXT = (".mp3",)
RX_STEPDIR = re.compile(r"^\d+[a-z]?$")  # patches/005, patches/12a


def skip_dir(rel, name):
    if name in SKIP_DIRS or rel in SKIP_PATHS:
        return True
    return rel.startswith("patches/") and bool(RX_STEPDIR.match(name))
TEXT_EXT = (".js", ".html", ".css", ".md", ".json", ".yml", ".yaml", ".txt", ".py")
JSON_BIG = 200 * 1024  # крупные json в карте только размером

RX_FUNC = re.compile(r"^(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)\s*\(")
RX_VAR = re.compile(r"^(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=")
RX_SCRIPT = re.compile(r"<script[^>]*\ssrc=[\"']([^\"']+)[\"']", re.I)
RX_LINK = re.compile(r"<link[^>]*\shref=[\"']([^\"']+)[\"']", re.I)


def read(path):
    with io.open(path, "r", encoding="utf-8", errors="replace", newline="") as f:
        return f.read()


def js_index(text, limit):
    out = []
    for n, line in enumerate(text.split("\n"), 1):
        line = line.rstrip("\r")
        m = RX_FUNC.match(line)
        kind = "fn"
        if not m:
            m = RX_VAR.match(line)
            kind = "var"
        if m:
            out.append((n, kind, m.group(1)))
    # компактно: fn:name:line ; var:name:line
    parts = ["%s:%s:%d" % (k, nm, ln) for ln, k, nm in out]
    s = " ".join(parts)
    if len(s) > limit:
        s = s[:limit].rsplit(" ", 1)[0] + " ...(обрезано)"
    return len(out), s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max", type=int, default=2500, help="символов индекса на файл")
    ap.add_argument("--out", default="REPO_MAP.md")
    a = ap.parse_args()
    root = os.getcwd()
    files = []
    for d, dirs, names in os.walk(root):
        drel = os.path.relpath(d, root).replace("\\", "/")
        pre = "" if drel == "." else drel + "/"
        dirs[:] = sorted(x for x in dirs if not skip_dir(pre + x, x))
        for nm in sorted(names):
            if nm.endswith(".orig") or nm == a.out or nm.lower().endswith(SKIP_EXT):
                continue
            p = os.path.join(d, nm)
            rel = os.path.relpath(p, root).replace("\\", "/")
            files.append((rel, p))

    out = ["# REPO_MAP (generated by tools/repo_map.py)", ""]
    out.append("## Файлы")
    out.append("")
    out.append("| файл | байт | строк |")
    out.append("|---|---:|---:|")
    texts = {}
    for rel, p in files:
        size = os.path.getsize(p)
        if rel.lower().endswith(TEXT_EXT) and not (
            rel.endswith(".json") and size > JSON_BIG
        ):
            t = read(p)
            texts[rel] = t
            out.append("| %s | %d | %d |" % (rel, size, t.count("\n") + 1))
        else:
            out.append("| %s | %d | - |" % (rel, size))
    for html in ("index.html", "scorch/index.html", "data/sandbox.html"):
        if html in texts:
            out.append("")
            out.append("## Порядок подключения: %s" % html)
            out.append("")
            for i, s in enumerate(RX_SCRIPT.findall(texts[html]), 1):
                out.append("%d. script %s" % (i, s))
            for s in RX_LINK.findall(texts[html]):
                out.append("- link %s" % s)
    out.append("")
    out.append("## Индекс верхнеуровневых символов (kind:name:line)")
    for rel in sorted(texts):
        if rel.endswith(".js"):
            n, s = js_index(texts[rel], a.max)
            out.append("")
            out.append("### %s (%d симв.)" % (rel, n))
            out.append(s)
        elif rel.endswith(".css"):
            rules = texts[rel].count("{")
            out.append("")
            out.append("### %s: ~%d блоков CSS" % (rel, rules))
    with io.open(os.path.join(root, a.out), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("Записано %s (%d файлов)" % (a.out, len(files)))


if __name__ == "__main__":
    main()
