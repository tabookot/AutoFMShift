#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""build_scorch.py - склеивает scorch.*.js в scorch/scorch.bundle.js.
  python tools/build_scorch.py          собрать
  python tools/build_scorch.py --check  код 1, если bundle устарел/отсутствует
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SC = os.path.join(ROOT, "scorch")
OUT = os.path.join(SC, "scorch.bundle.js")
PARTS = ["scorch.core.js", "scorch.music.js", "scorch.credits.js", "scorch.world.js", "scorch.ui.js"]
OPTIONAL = ("scorch.credits.js",)
HEAD = r"""// GENERATED by tools/build_scorch.py from scorch.*.js - DO NOT EDIT
(function(){
if (window.Scorch) return;
var __scBase = document.currentScript ? document.currentScript.src.replace(/[^\/]*$/, '') : '';
"""
TAIL = "\n})();\n"


def rd(path):
    with io.open(path, "r", encoding="utf-8-sig") as f:
        return f.read()


def build():
    chunks = []
    for name in PARTS:
        path = os.path.join(SC, name)
        if not os.path.isfile(path):
            if name in OPTIONAL:
                continue
            sys.exit("no file: " + path)
        chunks.append(rd(path).rstrip("\n"))
    return HEAD + "\n;\n".join(chunks) + TAIL


def main():
    data = build()
    if "--check" in sys.argv[1:]:
        if not os.path.isfile(OUT) or rd(OUT) != data:
            print("scorch.bundle.js is STALE: run python tools\\build_scorch.py")
            return 1
        print("scorch.bundle.js is up to date")
        return 0
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    print("written %s (%d bytes)" % (OUT, len(data.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
