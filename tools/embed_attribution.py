#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# embed_attribution.py - scorch/samples/ATTRIBUTION.txt -> scorch/scorch.credits.js
#   python tools/embed_attribution.py          write
#   python tools/embed_attribution.py --check  exit 1 if stale
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "scorch", "samples", "ATTRIBUTION.txt")
OUT = os.path.join(ROOT, "scorch", "scorch.credits.js")
HEAD = "// GENERATED by tools/embed_attribution.py from scorch/samples/ATTRIBUTION.txt - DO NOT EDIT\n"


def build():
    with io.open(SRC, "r", encoding="utf-8-sig") as f:
        text = f.read()
    text = text.replace("\r\n", "\n").strip("\n")
    return HEAD + "const SC_CREDITS = " + json.dumps(text, ensure_ascii=True) + ";\n"


def main():
    if not os.path.isfile(SRC):
        sys.exit("no file: " + SRC)
    data = build()
    if "--check" in sys.argv[1:]:
        cur = None
        if os.path.isfile(OUT):
            with io.open(OUT, "r", encoding="utf-8") as f:
                cur = f.read()
        if cur != data:
            print("scorch.credits.js is STALE: run python tools\\embed_attribution.py")
            return 1
        print("scorch.credits.js is up to date")
        return 0
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    print("written %s (%d bytes)" % (OUT, len(data.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
